-- Apply every roster snapshot not yet applied, oldest first. Returns counts.
CREATE OR REPLACE FUNCTION "Dimension"."LoadEmployee"() RETURNS jsonb
LANGUAGE plpgsql AS $$
DECLARE
    snapshot   record;
    history_start timestamp;
    applied_to timestamp;
    n int;
    n_snapshots int := 0;
    n_closed    int := 0;
    n_versions  int := 0;
    n_deleted   int := 0;
BEGIN
    SELECT "HistoryStartUtc", "LastSnapshotUtc" INTO history_start, applied_to
    FROM "Integration"."DimensionLoad" WHERE "TableName" = 'Dimension.Employee' FOR UPDATE;

    CREATE TEMP TABLE IF NOT EXISTS employee_snapshot (
        "EmployeeId" text PRIMARY KEY, "FirstName" text, "LastName" text, "JobTitle" text,
        "SupervisorEmployeeId" text, "IsActive" boolean, "PositionCode" text,
        "PositionJobTitle" text, "RowHash" text
    ) ON COMMIT DROP;
    CREATE TEMP TABLE IF NOT EXISTS employee_gone (LIKE "Dimension"."Employee") ON COMMIT DROP;

    FOR snapshot IN
        SELECT DISTINCT "FileId", "SnapshotUtc"
        FROM "Paylocity"."EmployeeInformationSnapshot"
        WHERE "SnapshotUtc" >= coalesce(history_start, '-infinity')
          AND "SnapshotUtc" >  coalesce(applied_to, '-infinity')
        ORDER BY "SnapshotUtc", "FileId"
    LOOP
        n_snapshots := n_snapshots + 1;

        TRUNCATE employee_snapshot;
        INSERT INTO employee_snapshot
        SELECT DISTINCT ON ("EmployeeId")
               "EmployeeId", "FirstName", "LastName", "JobTitle", "SupervisorEmployeeId", "IsActive",
               "PositionCode", "PositionJobTitle",
               md5(jsonb_build_array("FirstName", "LastName", "JobTitle", "SupervisorEmployeeId",
                                     "IsActive", "PositionCode", "PositionJobTitle")::text)
        FROM "Paylocity"."EmployeeInformationSnapshot"
        WHERE "FileId" = snapshot."FileId" AND "EmployeeId" IS NOT NULL
        ORDER BY "EmployeeId";

        -- Close the current version of anyone whose attributes changed, or who is
        -- back after being deleted.
        UPDATE "Dimension"."Employee" AS e
        SET "ValidTo" = snapshot."SnapshotUtc", "IsCurrent" = false, "UpdatedAt" = now()
        FROM employee_snapshot AS s
        WHERE e."EmployeeId" = s."EmployeeId" AND e."IsCurrent" AND e."EmployeeKey" > 0
          AND (e."RowHash" <> s."RowHash" OR e."IsDeleted");
        GET DIAGNOSTICS n = ROW_COUNT; n_closed := n_closed + n;

        -- A new current version for everyone in the roster without one: new
        -- employees, plus those just closed above.
        INSERT INTO "Dimension"."Employee"
            ("EmployeeId", "FirstName", "LastName", "FullName", "JobTitle", "SupervisorEmployeeId",
             "IsActive", "PositionCode", "PositionJobTitle", "ValidFrom", "IsCurrent", "RowHash", "SourceFileId")
        SELECT s."EmployeeId", s."FirstName", s."LastName",
               nullif(concat_ws(' ', s."FirstName", s."LastName"), ''),
               s."JobTitle", s."SupervisorEmployeeId", s."IsActive", s."PositionCode", s."PositionJobTitle",
               snapshot."SnapshotUtc", true, s."RowHash", snapshot."FileId"
        FROM employee_snapshot AS s
        WHERE NOT EXISTS (SELECT 1 FROM "Dimension"."Employee" AS e
                          WHERE e."EmployeeId" = s."EmployeeId" AND e."IsCurrent");
        GET DIAGNOSTICS n = ROW_COUNT; n_versions := n_versions + n;

        -- Soft delete anyone current who is no longer in the roster: close their
        -- version, then add a current copy marked deleted.
        TRUNCATE employee_gone;
        WITH closed AS (
            UPDATE "Dimension"."Employee" AS e
            SET "ValidTo" = snapshot."SnapshotUtc", "IsCurrent" = false, "UpdatedAt" = now()
            WHERE e."IsCurrent" AND NOT e."IsDeleted" AND e."EmployeeKey" > 0
              AND NOT EXISTS (SELECT 1 FROM employee_snapshot AS s WHERE s."EmployeeId" = e."EmployeeId")
            RETURNING e.*
        )
        INSERT INTO employee_gone SELECT * FROM closed;

        INSERT INTO "Dimension"."Employee"
            ("EmployeeId", "FirstName", "LastName", "FullName", "JobTitle", "SupervisorEmployeeId",
             "IsActive", "PositionCode", "PositionJobTitle", "IsDeleted", "ValidFrom", "IsCurrent",
             "RowHash", "SourceFileId")
        SELECT g."EmployeeId", g."FirstName", g."LastName", g."FullName", g."JobTitle", g."SupervisorEmployeeId",
               g."IsActive", g."PositionCode", g."PositionJobTitle", true, snapshot."SnapshotUtc", true,
               g."RowHash", snapshot."FileId"
        FROM employee_gone AS g;
        GET DIAGNOSTICS n = ROW_COUNT; n_deleted := n_deleted + n;

        UPDATE "Integration"."DimensionLoad"
        SET "LastSnapshotUtc" = snapshot."SnapshotUtc"
        WHERE "TableName" = 'Dimension.Employee';
    END LOOP;

    UPDATE "Integration"."DimensionLoad" SET "LastLoadedAt" = now() WHERE "TableName" = 'Dimension.Employee';

    RETURN jsonb_build_object(
        'snapshots_applied', n_snapshots,
        'new_employees',     n_versions - n_closed,
        'changed',           n_closed,
        'deleted',           n_deleted);
END;
$$;
