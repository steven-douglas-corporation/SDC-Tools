-- DataWarehouse (PostgreSQL): dimensions.
--
-- Run after 02_paylocity_staging.sql, as the database owner. Safe to re-run:
-- tables and seed rows are only created when missing, and the load functions
-- are CREATE OR REPLACE. Loading happens in "Integration"."RefreshWarehouse"()
-- (04_facts.sql), which the loader calls at the end of every run.
--
-- Every dimension has an "Unknown" row with key -1, so a fact row whose
-- employee or date can't be matched still loads and is easy to find.

CREATE SCHEMA IF NOT EXISTS "Dimension";

-- Where each history-keeping dimension has got to, and where its history starts.
CREATE TABLE IF NOT EXISTS "Integration"."DimensionLoad" (
    "TableName"       text PRIMARY KEY,
    "HistoryStartUtc" timestamp,      -- snapshots before this are ignored
    "LastSnapshotUtc" timestamp,      -- newest snapshot applied so far
    "LastLoadedAt"    timestamptz,
    "Notes"           text
);

-- ── Date ────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS "Dimension"."Date" (
    "DateKey"     integer PRIMARY KEY,           -- yyyymmdd, e.g. 20261004; -1 = Unknown
    "Date"        date UNIQUE,
    "Year"        integer,
    "Quarter"     integer,
    "MonthNumber" integer,
    "MonthName"   text,
    "YearMonth"   text,                          -- '2026-10'
    "MonthStart"  date,
    "WeekStart"   date,                          -- Monday
    "IsoWeek"     integer,
    "DayOfWeek"   integer,                       -- 1 = Monday ... 7 = Sunday
    "DayName"     text,
    "IsWeekday"   boolean
);

INSERT INTO "Dimension"."Date" ("DateKey", "MonthName", "DayName")
VALUES (-1, 'Unknown', 'Unknown')
ON CONFLICT ("DateKey") DO NOTHING;

INSERT INTO "Dimension"."Date"
SELECT to_char(d, 'YYYYMMDD')::integer,
       d,
       extract(year FROM d)::integer,
       extract(quarter FROM d)::integer,
       extract(month FROM d)::integer,
       to_char(d, 'FMMonth'),
       to_char(d, 'YYYY-MM'),
       date_trunc('month', d)::date,
       date_trunc('week', d)::date,
       extract(week FROM d)::integer,
       extract(isodow FROM d)::integer,
       to_char(d, 'FMDay'),
       extract(isodow FROM d) < 6
FROM generate_series(date '2015-01-01', date '2035-12-31', interval '1 day') AS g (ts),
     LATERAL (SELECT g.ts::date AS d) AS x
ON CONFLICT ("DateKey") DO NOTHING;

-- ── Employee ────────────────────────────────────────────────────────────────
-- Type 2: a new version every time a tracked attribute changes, so facts can
-- see the employee as they were on the day. One row per employee per version:
--   "ValidFrom"/"ValidTo"  when this version applied ("ValidTo" NULL = current)
--   "IsCurrent"            exactly one current version per employee
--   "IsDeleted"            soft delete: the employee disappeared from the
--                          Paylocity roster. Their history stays; the current
--                          version is a copy marked deleted. If they reappear,
--                          a new live version starts.
-- "IsActive" is Paylocity's own active flag (the roster also lists inactive
-- people); it is an attribute, not a delete.

CREATE TABLE IF NOT EXISTS "Dimension"."Employee" (
    "EmployeeKey"          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EmployeeId"           text        NOT NULL,     -- Paylocity Employee Id
    "FirstName"            text,
    "LastName"             text,
    "FullName"             text,
    "JobTitle"             text,
    "SupervisorEmployeeId" text,
    "IsActive"             boolean,
    "PositionCode"         text,
    "PositionJobTitle"     text,
    "IsDeleted"            boolean     NOT NULL DEFAULT false,
    "ValidFrom"            timestamp   NOT NULL,     -- UTC, the roster snapshot's time
    "ValidTo"              timestamp,
    "IsCurrent"            boolean     NOT NULL,
    "RowHash"              text        NOT NULL,     -- of the tracked attributes
    "SourceFileId"         bigint,
    "InsertedAt"           timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt"            timestamptz
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_Employee_Current"
    ON "Dimension"."Employee" ("EmployeeId") WHERE "IsCurrent";
CREATE INDEX IF NOT EXISTS "IX_Employee_Version" ON "Dimension"."Employee" ("EmployeeId", "ValidFrom");

